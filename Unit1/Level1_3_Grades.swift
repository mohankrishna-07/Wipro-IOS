// Unit1 Task 1.3 - Given a student's mark (0–100), print the grade using if / else if.
import Foundation

let mark = 85 // change to test
if mark >= 90 {
    print("Grade: A")
} else if mark >= 80 {
    print("Grade: B")
} else if mark >= 70 {
    print("Grade: C")
} else if mark >= 60 {
    print("Grade: D")
} else {
    print("Grade: F")
}
